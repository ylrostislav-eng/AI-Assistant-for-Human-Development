-- P1-02: чтение сессии до аутентификации (docs/09, раздел 2).
--
-- Задача. Чтобы найти сессию по предъявленному refresh-токену, её нужно
-- прочитать раньше, чем известен пользователь, а политика изоляции требует
-- контекст пользователя. Без решения вход невозможен: политика закрывает
-- строку, которую и нужно прочитать для входа.
--
-- Отвергнутый вариант: функция SECURITY DEFINER. Она обходит политики целиком,
-- и её владельцу нужны права шире, чем у приложения; при FORCE RLS владелец
-- таблицы всё равно подчиняется политикам, поэтому владельцем пришлось бы
-- делать отдельную привилегированную роль. Это работающее, но более широкое
-- отверстие: ошибка в теле функции открывает всю таблицу.
--
-- Выбранный вариант: политика по предъявленному хешу. Вызывающий видит ровно
-- ту строку, хеш которой смог предъявить, то есть токен которой у него уже
-- есть. Никаких новых ролей и никакого обхода RLS: право доступа — владение
-- самим токеном. Подбор невозможен, токен содержит 32 случайных байта.
--
-- Политика разрешающая и действует вместе с политикой владельца: обычные
-- запросы пользователя продолжают работать по app.user_id.

CREATE POLICY sessions_lookup_by_hash ON sessions
  FOR SELECT
  USING (refresh_hash = NULLIF(current_setting('app.refresh_hash', true), ''));
