-- T-00b: у аренды задания появляется владелец.

-- Дефект R3 (docs/15-backend-review.md): `completeJob`/`failJob` меняли строку
-- по одному идентификатору, без проверки, чья сейчас аренда. Ожившей после
-- паузы процесс помечал done работу, которую уже взял и, возможно, прямо
-- сейчас выполняет другой: событие оставалось недоставленным, а повтор был
-- отменён. Поздняя неудача так же возвращала чужую работу в pending, и её
-- брал третий worker.
--
-- lease_token — маркер владения: он выдаётся при каждом резервировании и
-- проверяется при завершении. Прежний исполнитель предъявляет старый маркер и
-- не меняет ничего. Отдельной таблицы аренд не заводится: она потребовала бы
-- второго согласованного изменения там, где хватает одного столбца.

ALTER TABLE jobs ADD COLUMN lease_token UUID;

-- NOT VALID намеренно: задания, уже находившиеся в работе на момент миграции,
-- маркера не имеют и доказать владение не могут. Переписывать их статус здесь
-- нельзя — работа могла идти в этот момент. Их аренда истечёт сама, после чего
-- задание будет зарезервировано заново уже с маркером; ограничение начнёт
-- действовать для них при первом же изменении строки.
ALTER TABLE jobs ADD CONSTRAINT jobs_running_has_lease
  CHECK (status <> 'running' OR (lease_token IS NOT NULL AND lease_until IS NOT NULL))
  NOT VALID;
