-- T-00d: интервалы пользовательских дней не пересекаются.
--
-- Дефект R5 (docs/15-backend-review.md): `ON CONFLICT (user_id, local_date)`
-- ловит совпадение даты, а не наложение отрезков. Смена границы дня с 04:00 на
-- 00:00 создавала второй день, пересекающийся с первым на четыре часа: одно
-- мгновение принадлежало сразу двум дням. Для будущих корзин наград это
-- двойной дневной бюджет за одни и те же часы.
--
-- Прикладное правило переходного дня живёт в user-days.ts, но полагаться
-- только на него нельзя: следующий обработчик, пишущий в user_days напрямую,
-- о нём не узнает. Ограничение исключения делает пересечение невозможным на
-- уровне базы.
--
-- Интервал полуоткрытый `[)`: день, начинающийся ровно в конце предыдущего,
-- пересечением не считается — именно так дни и идут встык.
--
-- btree_gist нужен, чтобы сравнивать user_id обычным равенством внутри
-- индекса GiST. Расширение доверенное, его создаёт владелец базы.

CREATE EXTENSION IF NOT EXISTS btree_gist;

ALTER TABLE user_days ADD CONSTRAINT user_days_no_overlap
  EXCLUDE USING gist (
    user_id WITH =,
    tstzrange(starts_at, ends_at, '[)') WITH &&
  );
