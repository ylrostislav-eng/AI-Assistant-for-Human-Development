import type { Database } from '../../src/shared/db/pool.ts';

/**
 * Полный сброс схемы перед проверками миграций.
 *
 * Раньше каждый файл удалял собственный список таблиц, и результат зависел от
 * порядка запуска: файл, удаливший только свои таблицы, оставлял чужие, и
 * следующий прогон миграций падал на «таблица уже существует». Список таблиц
 * пришлось бы обновлять в каждом файле при каждой новой миграции — ровно та
 * ошибка, которую никто не заметит, пока порядок не изменится.
 */
export async function resetSchema(db: Database): Promise<void> {
  await db.query('DROP SCHEMA public CASCADE');
  await db.query('CREATE SCHEMA public');
}
